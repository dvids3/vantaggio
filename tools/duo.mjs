import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const problems = [];
page.on('pageerror', (e) => problems.push(e.message));
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'Dos jugadores', exact: true }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'Siguiente', exact: true }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/flow/12-duo-p2.png' });
await page.getByRole('button', { name: 'Jugar', exact: true }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/flow/13-duo-opciones.png' });
await page.getByRole('button', { name: 'Jugar', exact: true }).click();
await page.waitForTimeout(1600);
await page.keyboard.down('KeyD');
await page.waitForTimeout(700);
await page.keyboard.up('KeyD');
await page.waitForTimeout(200);
await page.screenshot({ path: '/tmp/flow/14-duo-partido.png' });
await browser.close();
console.log(problems.length ? problems.join('\n') : 'ok');
