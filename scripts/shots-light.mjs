import { chromium } from 'playwright';
const url = process.env.URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(url, { waitUntil: 'networkidle' });
await page.waitForTimeout(2200);
await page.getByText('Nuevo campeonato', { exact: true }).click();
await page.waitForTimeout(350);
await page.getByText('Normal', { exact: false }).first().click();
await page.getByText('Siguiente', { exact: true }).click();
await page.waitForTimeout(300);
await page.getByText('Sorteo real', { exact: false }).first().click();
await page.waitForTimeout(700);
for (let i = 0; i < 48; i++) {
  const name = (await page.locator('.team-name').first().textContent()) ?? '';
  if (name.trim() === 'Argentina') break;
  await page.getByLabel('Selección siguiente').click();
  await page.waitForTimeout(120);
}
await page.waitForTimeout(900);
await page.screenshot({ path: 'docs/capturas/e-equipo.jpg', type: 'jpeg', quality: 90 });
await page.getByText('Jugar', { exact: true }).first().click();
await page.waitForSelector('.screen.groups', { timeout: 8000 });
await page.waitForTimeout(300);
await page.getByText('Siguiente', { exact: true }).last().click();
await page.waitForSelector('.screen.options', { timeout: 8000 });
await page.waitForTimeout(700);
await page.screenshot({ path: 'docs/capturas/e-opciones.jpg', type: 'jpeg', quality: 90 });
await page.getByText('Jugar', { exact: true }).last().click();
await page.waitForSelector('.screen.match canvas.stage', { timeout: 8000 });
await page.waitForTimeout(900);
await page.screenshot({ path: 'docs/capturas/e-partido.jpg', type: 'jpeg', quality: 90 });
await page.screenshot({ path: 'docs/capturas/e-cabezones.png', clip: { x: 330, y: 470, width: 340, height: 260 } });
await page.screenshot({ path: 'docs/capturas/e-cabezones2.png', clip: { x: 950, y: 470, width: 340, height: 260 } });
console.log('errores:', errors.length ? errors : 'ninguno');
await browser.close();
